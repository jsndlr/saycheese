"use node";

import { VARIANTS, WEBP_QUALITY } from "@saycheese/core/limits";
import { createHash } from "node:crypto";
import sharp from "sharp";

import { components, internal } from "../_generated/api";
import type { Id } from "../_generated/dataModel";
import type { ActionCtx } from "../_generated/server";
import { internalAction } from "../_generated/server";
import { createAuth } from "../auth";
import { env } from "../env";
import { assertSeedDeployment } from "../lib/seedGuard";
import { SEED_IMAGES, SEED_SOURCE, type SeedImage } from "../model/seed";
import type { SeedImageRow } from "./seedData";

/**
 * Seeds a development deployment with a signable demo account and five images
 * that cover every UI state. Safe to run repeatedly: accounts are looked up by
 * email and images by (userId, sha256), and generated bytes are deterministic.
 */

const DEMO_EMAIL = "demo@saycheese.dev";
const DEMO_NAME = "Demo User";
/** Dev-only fallback. The account can only exist on a localhost deployment. */
const DEFAULT_DEMO_PASSWORD = "saycheese-demo-2026";
const IMAGE_SPACING_MS = 3 * 60_000;

type DemoUser = { _id: string };

async function findDemoUser(ctx: ActionCtx): Promise<DemoUser | null> {
  return (await ctx.runQuery(components.betterAuth.adapter.findOne, {
    model: "user",
    where: [{ field: "email", value: DEMO_EMAIL }],
  })) as DemoUser | null;
}

/**
 * Creates the demo account through Better Auth's own sign-up API, so the
 * password hash and account rows are exactly what the sign-in form produces.
 */
async function ensureDemoUser(
  ctx: ActionCtx,
): Promise<{ userId: string; userCreated: boolean }> {
  const existing = await findDemoUser(ctx);
  if (existing !== null) {
    return { userId: existing._id, userCreated: false };
  }

  const password = env.SEED_DEMO_PASSWORD ?? DEFAULT_DEMO_PASSWORD;
  try {
    await createAuth(ctx).api.signUpEmail({
      body: { email: DEMO_EMAIL, password, name: DEMO_NAME },
    });
  } catch (error) {
    // A concurrent seed may have created it between the lookup and the call.
    const raced = await findDemoUser(ctx);
    if (raced !== null) {
      return { userId: raced._id, userCreated: false };
    }
    throw error;
  }

  const created = await findDemoUser(ctx);
  if (created === null) {
    throw new Error(`Better Auth reported success but ${DEMO_EMAIL} cannot be found.`);
  }
  return { userId: created._id, userCreated: true };
}

function gradientPixels(spec: SeedImage): Buffer {
  const { width, height } = SEED_SOURCE;
  const { from, to } = spec.palette;
  const pixels = Buffer.alloc(width * height * 3);
  for (let y = 0; y < height; y += 1) {
    const vertical = y / (height - 1);
    for (let x = 0; x < width; x += 1) {
      const t = (x / (width - 1) + vertical) / 2;
      const offset = (y * width + x) * 3;
      pixels[offset] = Math.round(from[0] + (to[0] - from[0]) * t);
      pixels[offset + 1] = Math.round(from[1] + (to[1] - from[1]) * t);
      pixels[offset + 2] = Math.round(from[2] + (to[2] - from[2]) * t);
    }
  }
  return pixels;
}

/** Deterministic PNG: sharp/libvips writes no timestamp metadata. */
async function renderSource(spec: SeedImage): Promise<Buffer> {
  const { width, height } = SEED_SOURCE;
  return await sharp(gradientPixels(spec), {
    raw: { width, height, channels: 3 },
  })
    .png({ compressionLevel: 9 })
    .toBuffer();
}

async function storeBlob(
  ctx: ActionCtx,
  bytes: Buffer,
  type: string,
): Promise<Id<"_storage">> {
  return await ctx.storage.store(
    new Blob([new Uint8Array(bytes)], { type }),
  );
}

async function buildPlan(
  ctx: ActionCtx,
  spec: SeedImage,
  createdAt: number,
  source: Buffer,
  sha256: string,
): Promise<SeedImageRow> {
  const { width, height } = SEED_SOURCE;
  const plan: SeedImageRow = {
    sha256,
    mime: "image/png",
    bytes: source.length,
    width,
    height,
    status: spec.status,
    failureCode: spec.failureCode,
    createdAt,
    score: spec.score,
  };

  if (spec.hasVariants) {
    const variants = await Promise.all(
      VARIANTS.map((variant) =>
        sharp(source)
          .resize({
            width: variant.edge,
            height: variant.edge,
            fit: "inside",
            withoutEnlargement: true,
          })
          .webp({ quality: WEBP_QUALITY })
          .toBuffer(),
      ),
    );
    const [large, medium, thumb] = await Promise.all(
      variants.map((bytes) => storeBlob(ctx, bytes, "image/webp")),
    );
    plan.storageId = large;
    plan.previewId = medium;
    plan.thumbId = thumb;
  } else {
    // Pending and failed images keep the raw upload and have no variants.
    plan.rawStorageId = await storeBlob(ctx, source, "image/png");
  }

  return plan;
}

export const run = internalAction({
  args: {},
  handler: async (ctx) => {
    assertSeedDeployment(env.SITE_URL);

    const { userId, userCreated } = await ensureDemoUser(ctx);

    const existingHashes = await ctx.runQuery(internal.internal.seedData.hashes, {
      userId,
    });
    const existing = new Set(existingHashes);

    const base = Date.now();
    const plans: SeedImageRow[] = [];
    let imagesSkipped = 0;

    for (const [index, spec] of SEED_IMAGES.entries()) {
      const createdAt = base - index * IMAGE_SPACING_MS;
      const source = await renderSource(spec);
      const sha256 = createHash("sha256").update(source).digest("hex");
      if (existing.has(sha256)) {
        // Render only: no storage object is created for an image that exists.
        imagesSkipped += 1;
        continue;
      }
      plans.push(await buildPlan(ctx, spec, createdAt, source, sha256));
    }

    let imagesCreated = 0;
    if (plans.length > 0) {
      const result = await ctx.runMutation(internal.internal.seedData.commit, {
        userId,
        images: plans,
      });
      imagesCreated = result.imagesCreated;
      imagesSkipped += result.imagesSkipped;
      for (const storageId of result.unusedStorageIds) {
        await ctx.storage.delete(storageId);
      }
    }

    return { userCreated, imagesCreated, imagesSkipped };
  },
});